const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    const stored = localStorage.getItem("yatt-lang");
    return stored === "en" ? "en" : "es";
  });

  useEffect(() => {
    localStorage.setItem("yatt-lang", lang);
    document.documentElement.lang = lang === "en" ? "en" : "es";
  }, [lang]);

  const value = useMemo<I18nValue>(
    () => ({
      lang,
      setLang,
      t: (key: string, ...args: Array<string | number>) => {
        const dict = lang === "en" ? EN_DICT : ES_DICT;
        const es = ES_DICT[key];
        const raw = dict[key] ?? es ?? key;
        return args.length > 0 ? format(raw, args) : raw;
      },
    }),
    [lang],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n debe usarse dentro de <I18nProvider>");
  return value;
}